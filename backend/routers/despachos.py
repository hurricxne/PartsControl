@router.get("/counts")
def counts(db: Session = Depends(get_db), current_user: User = Depends(get_current_user)):
    ocs = db.query(OcCliente).join(OcCliente.cotizacion).all()
    # Estados de los ítems de TODAS las cotizaciones en una sola query
    # (antes: una query por OC → cientos de queries con el historial cargado)
    cot_ids = [oc.cotizacion_id for oc in ocs if oc.cotizacion_id]
    estados_por_cot: dict = {}
    if cot_ids:
        rows = (
            db.query(ItemCotizacion.cotizacion_id, ItemCotizacion.estado_item)
            .filter(ItemCotizacion.cotizacion_id.in_(cot_ids))
            .all()
        )
        for cot_id, estado in rows:
            estados_por_cot.setdefault(cot_id, []).append(estado)
    ocs_listas = 0
    items_listos = 0
    items_despachados = 0
    for oc in ocs:
        if not oc.cotizacion:
            continue
        estados = estados_por_cot.get(oc.cotizacion_id, [])
        en_b = sum(1 for e in estados if e == "en_bodega")
        desp = sum(1 for e in estados if e == "despachado")
        if en_b > 0:
            ocs_listas += 1
        items_listos += en_b
        items_despachados += desp
    return {
        "ocs_listas": ocs_listas,
        "items_listos": items_listos,
        "items_despachados": items_despachados,
    }


@router.get("/oc-clientes")
def oc_clientes(
    tab: str = "listas",
    q: Optional[str] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """List OCs by tab: listas | en_curso | historial"""
    ocs = db.query(OcCliente).join(OcCliente.cotizacion).all()

    # Precarga en LOTE (antes: hasta 3 queries por OC dentro del loop):
    # ítems por cotización, fichas de cliente por RUT y qué OCs tienen
    # despachos abiertos (en_preparacion) o cerrados (despachado).
    cot_ids = [oc.cotizacion_id for oc in ocs if oc.cotizacion_id]
    items_por_cot: dict = {}
    if cot_ids:
        for it in (
            db.query(ItemCotizacion)
            .filter(ItemCotizacion.cotizacion_id.in_(cot_ids))
            .all()
        ):
            items_por_cot.setdefault(it.cotizacion_id, []).append(it)
    ruts = {oc.cotizacion.rut_cliente for oc in ocs if oc.cotizacion and oc.cotizacion.rut_cliente}
    clientes_por_rut: dict = {}
    if ruts:
        for cli in db.query(Cliente).filter(Cliente.rut.in_(ruts)).all():
            clientes_por_rut[cli.rut] = cli
    oc_ids = [oc.id for oc in ocs]
    ocs_con_abierto, ocs_con_cerrado = set(), set()
    if oc_ids:
        estados_despacho = (
            db.query(Despacho.oc_cliente_id, Despacho.estado)
            .filter(
                Despacho.oc_cliente_id.in_(oc_ids),
                Despacho.estado.in_(("en_preparacion", "despachado")),
            )
            .all()
        )
        for oc_id, estado in estados_despacho:
            (ocs_con_abierto if estado == "en_preparacion" else ocs_con_cerrado).add(oc_id)

    result = []
    for oc in ocs:
        card = _serialize_oc_card(
            db, oc,
            items=items_por_cot.get(oc.cotizacion_id, []),
            clientes_por_rut=clientes_por_rut,
        )
        if not card:
            continue

        if tab == "listas":
            if card["items_en_bodega"] == 0:
                continue
            if card["estado"] == "completado":
                continue
        elif tab == "en_curso":
            if oc.id not in ocs_con_abierto:
                continue
        elif tab == "historial":
            if oc.id not in ocs_con_cerrado:
                continue
        else:
            raise HTTPException(400, f"tab inválido: {tab}")

        if q:
            ql = q.lower()
            haystack = " ".join(
                [
                    card.get("cliente") or "",
                    card.get("numero_oc") or "",
                    card.get("numero_cotizacion") or "",
                    card.get("rut_cliente") or "",
                ]
            ).lower()
            if ql not in haystack:
                continue

        result.append(card)
    # Sort by fecha_entrega ascending (urgent first), nulls last
    result.sort(key=lambda c: (c.get("fecha_entrega") is None, c.get("fecha_entrega") or ""))
    return result


