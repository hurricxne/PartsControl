def _exists_in_docs(value: str) -> bool:
    """Check if value corresponds to a real file in DOCS_DIR (path-traversal safe)"""
    if not value or "/" in value or "\\" in value or ".." in value:
        return False
    candidate = os.path.abspath(os.path.join(_DOCS_DIR, value))
    if not candidate.startswith(_DOCS_DIR + os.sep):
        return False
    return os.path.isfile(candidate)


