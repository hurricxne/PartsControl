# Heuristic: a value generated by /docs/upload is a 32-hex UUID + extension
_UPLOAD_FILE_RE = re.compile(r"^[0-9a-f]{32}\.[A-Za-z0-9]{2,5}$")
_DOCS_DIR = os.path.abspath(
    os.path.join(os.path.dirname(os.path.dirname(__file__)), "uploads", "docs")
)


def _looks_like_upload(value: Optional[str]) -> bool:
    return bool(value and _UPLOAD_FILE_RE.match(value.strip()))


def _exists_in_docs(value: str) -> bool:
    """Check if value corresponds to a real file in DOCS_DIR (path-traversal safe)"""
    if not value or "/" in value or "\\" in value or ".." in value:
        return False
    candidate = os.path.abspath(os.path.join(_DOCS_DIR, value))
    if not candidate.startswith(_DOCS_DIR + os.sep):
        return False
    return os.path.isfile(candidate)


