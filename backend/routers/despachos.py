@router.post("/")
def create_despacho(
    payload: DespachoCreate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    # El correlativo DSP-AAAA-#### se calcula sin lock: si dos despachos simultáneos
    # chocan en el UNIQUE de numero_despacho, se recalcula y se reintenta (máx. 3)
    # en vez de devolver un 500 al usuario.
    # Y el 1213/1205 se reintenta igual (paridad inversa con monza_router_despachos.py:673-685,
    # que lo ganó en la Fase 2): crear lockea los ÍTEMS primero y después las filas de
    # despacho, mientras cerrar/anular lockean el DESPACHO primero → orden inverso, ciclo
    # InnoDB. `cerrar` ya tiene este retry (ver más abajo); crear se quedó sin él y un deadlock
    # salía como 500 al usuario en vez de reintentarse solo.
    for _ in range(3):
        try:
            return _crear_despacho(db, payload, current_user)
        except IntegrityError as e:
            db.rollback()
            if "numero_despacho" not in str(getattr(e, "orig", e)):
                raise
        except OperationalError as e:
            db.rollback()
            code = getattr(getattr(e, "orig", None), "args", [None])[0]
            if code not in (1213, 1205):
                raise
    raise HTTPException(
        409, "No se pudo crear el despacho por creación simultánea de la misma OC: reintenta"
    )


def _crear_despacho(db: Session, payload: DespachoCreate, current_user: User):
    oc = db.query(OcCliente).filter(OcCliente.id == payload.oc_cliente_id).first()
    if not oc:
        raise HTTPException(404, "OC Cliente no encontrada")
    if not payload.items:
        raise HTTPException(400, "Debe incluir al menos 1 ítem")

    item_ids = [i.item_cotizacion_id for i in payload.items]
    # Una línea por ítem: dos líneas del mismo ítem burlarían la validación de
    # disponible (cada una se compararía sola contra el total).
    if len(set(item_ids)) != len(item_ids):
        raise HTTPException(400, "Hay ítems repetidos en el despacho: consolida la cantidad en una sola línea")
    # FOR UPDATE sobre los ítems: serializa despachos concurrentes de la misma OC
    # (el segundo espera aquí y valida contra lo que el primero ya commiteó).
    # populate_existing(): sin él, el identity map devolvería datos del snapshot viejo.
    items_db = (
        db.query(ItemCotizacion)
        .filter(
            ItemCotizacion.id.in_(item_ids),
            ItemCotizacion.cotizacion_id == oc.cotizacion_id,
        )
        .populate_existing()
        .with_for_update()
        .all()
    )
    if len(items_db) != len(set(item_ids)):
        raise HTTPException(400, "Hay ítems que no pertenecen a esta OC")

    items_by_id = {i.id: i for i in items_db}
    qty_already = _qty_already_dispatched(db, oc.id, con_lock=True)
    # Tope físico por lo RECIBIDO en bodega (recepción parcial ⇒ solo lo que llegó)
    recibidos = _qty_recibida_utilizable(db, item_ids)
    # El guard valida contra LA MISMA fórmula que pintan detalle/listado/panel
    # (_disponibles_por_item): si alguien la toca, el tope real y lo que ven las
    # pantallas se mueven JUNTOS — una copia local divergiría en silencio (sonda
    # S3 de test_listo_para_despachar.py). El estado ≠ en_bodega se sigue
    # validando antes, con su mensaje propio; para esas líneas el helper ya trae 0.
    disponibles = _disponibles_por_item(items_db, recibidos, qty_already)

    for item_in in payload.items:
        it = items_by_id.get(item_in.item_cotizacion_id)
        if not it:
            raise HTTPException(400, f"Ítem {item_in.item_cotizacion_id} no encontrado")
        if it.estado_item != "en_bodega":
            raise HTTPException(
                400,
                f"Ítem {it.numero_parte} no está disponible para despacho (estado: {it.estado_item})",
            )
        if item_in.qty_despachada <= 0:
            raise HTTPException(400, f"Cantidad inválida para {it.numero_parte}")
        if item_in.qty_despachada <= _TOL_QTY:
            # MISMA tolerancia que el cupo visible y que armar_lineas del DTE. Sin
            # esto, un payload de 7e-9 pasaba (`> 0` y `> disponible + 0.001` es
            # False con disponible 0) y creaba un DESPACHO ZOMBI: la guía SII lo
            # rechaza con «El despacho no tiene cantidades a despachar» (el
            # armador descarta la línea por qty <= TOL) y hay que anularlo a mano.
            # Mensaje PROPIO, no «Cantidad inválida»: el operador no tipeó mal.
            # El texto dice «mayor que», no «el mínimo es»: la condición es
            # `<= _TOL_QTY`, así que 0.001 EXACTO también se rechaza. Con la
            # redacción anterior el operador reintentaba justo el valor que el
            # guard no acepta y el sistema parecía roto.
            raise HTTPException(
                400,
                f"Cantidad demasiado pequeña para despachar {it.numero_parte} "
                f"({item_in.qty_despachada}): debe ser mayor que {_TOL_QTY}",
            )
        disponible = disponibles.get(it.id, 0)
        if item_in.qty_despachada > disponible + 0.001:
            # El tope se recalcula SOLO para elegir el mensaje (recibido parcial
            # vs cupo consumido) — la decisión de bloquear ya la tomó el helper.
            tope = _tope_fisico(it, recibidos)
            if tope < (it.cantidad or 0):
                raise HTTPException(
                    400,
                    f"Cantidad excede lo RECIBIDO en bodega para {it.numero_parte} "
                    f"(recibido: {tope}, disponible: {max(disponible, 0)})",
                )
            raise HTTPException(
                400,
                f"Cantidad excede disponible para {it.numero_parte} (disp: {disponible})",
            )

    despacho = Despacho(
        numero_despacho=_next_numero_despacho(db),
        oc_cliente_id=payload.oc_cliente_id,
        numero_guia=payload.numero_guia,
        transportista=payload.transportista,
        numero_expedicion=payload.numero_expedicion,
        # Normalizado al entrar (trim, ""→None, tope 50): el operador empaca
        # MIENTRAS crea el despacho, así que el bulto puede venir desde el inicio.
        bulto_numero=_normalizar_bulto(payload.bulto_numero),
        contacto_destinatario=payload.contacto_destinatario,
        direccion_entrega=payload.direccion_entrega,
        observaciones=payload.observaciones,
        estado="en_preparacion",
        usuario_creacion_id=getattr(current_user, "id", None),
    )
    db.add(despacho)
    db.flush()

    for item_in in payload.items:
        db.add(
            DespachoItem(
                despacho_id=despacho.id,
                item_cotizacion_id=item_in.item_cotizacion_id,
                qty_despachada=item_in.qty_despachada,
            )
        )

    db.commit()
    db.refresh(despacho)
    return {"id": despacho.id, "numero_despacho": despacho.numero_despacho}


