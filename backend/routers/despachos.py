@router.put("/{despacho_id}")
def update_despacho(
    despacho_id: int,
    payload: DespachoUpdate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    d = db.query(Despacho).filter(Despacho.id == despacho_id).first()
    if not d:
        raise HTTPException(404, "Despacho no encontrado")
    if d.estado == "anulado":
        raise HTTPException(400, "No se puede editar un despacho anulado")
    # Los datos de cabecera (transportista, N° guía, N° de expedición, contacto, dirección,
    # observaciones) pueden completarse/corregirse aunque el despacho ya esté cerrado o firmado:
    # el N° de expedición suele llegar del courier DESPUÉS del despacho.
    data = payload.dict(exclude_unset=True)
    # Excepción: con guía electrónica viva, numero_guia es el folio del SII y no se pisa a mano.
    if "numero_guia" in data:
        _rechazar_si_pisa_folio(db, d, data["numero_guia"])
    # fecha_guia llega como texto y la columna es Date: se convierte y valida ANTES del
    # setattr genérico (si no, SQLAlchemy guardaría el string crudo). Se saca del dict para
    # que el bucle de abajo no la pise con el valor sin parsear.
    if "fecha_guia" in data:
        d.fecha_guia = _parse_fecha_guia(data.pop("fecha_guia"))
    # bulto_numero se normaliza ANTES del setattr genérico (trim, ""→None, guard de
    # largo con 400): si llegara crudo, un texto de 51 chars recién reventaría en el
    # commit con un DataError críptico. La edición vale en todo estado salvo anulado
    # (el guard de arriba ya lo bloquea): el rotulado de la caja se corrige incluso
    # con el despacho cerrado, igual que el N° de expedición.
    if "bulto_numero" in data:
        data["bulto_numero"] = _normalizar_bulto(data["bulto_numero"])
    for field, value in data.items():
        setattr(d, field, value)
    db.commit()
    return {"ok": True}


@router.post("/{despacho_id}/cerrar")
def cerrar_despacho(
    despacho_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    # Retry 1213/1205 (regla de la casa): cerrar ahora toma locks (despacho + ítems)
    # y puede caer víctima de un deadlock contra crear/anular concurrentes.
    for _ in range(3):
        try:
            return _cerrar_despacho_tx(db, despacho_id)
        except OperationalError as e:
            db.rollback()
            code = getattr(getattr(e, "orig", None), "args", [None])[0]
            if code not in (1213, 1205):
                raise
    raise HTTPException(409, "Conflicto de concurrencia al cerrar el despacho: reintenta")


def _cerrar_despacho_tx(db: Session, despacho_id: int):
    # FOR UPDATE sobre el despacho: serializa contra anular_despacho (que también
    # lockea) y contra la emisión de la guía. populate_existing(): datos frescos
    # aunque el snapshot REPEATABLE READ sea anterior.
    d = (
        db.query(Despacho)
        .filter(Despacho.id == despacho_id)
        .populate_existing()
        .with_for_update()
        .first()
    )
    if not d:
        raise HTTPException(404, "Despacho no encontrado")
    if d.estado != "en_preparacion":
        raise HTTPException(400, "Solo se pueden cerrar despachos en preparación")

    # Ancla canónica de la casa (patrón recepcion_nacional._cerrar): lockear los
    # ItemCotizacion afectados en UNA query, orden id ASC, antes de mutar estados.
    item_ids = sorted({di.item_cotizacion_id for di in d.items if di.item_cotizacion_id})
    if item_ids:
        (
            db.query(ItemCotizacion)
            .filter(ItemCotizacion.id.in_(item_ids))
            .order_by(ItemCotizacion.id.asc())
            .populate_existing()
            .with_for_update()
            .all()
        )

    # CERRAR PRIMERO y flush: la cobertura de abajo cuenta SOLO despachos cerrados
    # (incluido este). Sin esto, la última tanda nunca voltearía la línea; y contar
    # abiertos (bug G16) marcaba 'despachado' prematuro con tandas en preparación.
    d.estado = "despachado"
    # DEUDA (anotada, no tocada acá): `datetime.now()` deja un instante NAIVE con
    # el reloj del server — en producción UTC, en un equipo local hora de Chile.
    # Ese dato lo leen varios consumidores (listado, mail, suites), así que pasarlo
    # a UTC explícito es una decisión aparte. Quien necesite el DÍA del negocio NO
    # debe interpretar esta columna por su cuenta: usa _cerrado_hoy(), que hace la
    # conversión a hora de Chile en UN solo lugar.
    d.fecha_despacho = datetime.now()
    db.flush()

    # Recolectar embarques afectados para evaluar auto-transición a "despachado"
    embarque_ids_afectados = set()
    # Cantidad acumulada por ítem en los despachos CERRADOS de la OC (incluye este).
    # La línea pasa a "despachado" solo cuando queda cubierta completa: un cierre
    # parcial deja el remanente en bodega, despachable y facturable después.
    qty_total = _qty_dispatched_closed(db, d.oc_cliente_id, con_lock=True)
    for di in d.items:
        it = di.item_cotizacion
        if it and it.estado_item == "en_bodega":
            if qty_total.get(it.id, 0) + 0.001 < (it.cantidad or 0):
                continue
            it.estado_item = "despachado"
            # Buscar el embarque que trajo este item
            ei = (
                db.query(EmbarqueItem)
                .filter(EmbarqueItem.item_cotizacion_id == it.id)
                .first()
            )
            if ei:
                embarque_ids_afectados.add(ei.embarque_id)

    # Auto-transición: si TODOS los items de un embarque están despachados,
    # marcar el embarque como "despachado"
    db.flush()
    for emb_id in embarque_ids_afectados:
        item_ids_emb = [
            r[0] for r in db.query(EmbarqueItem.item_cotizacion_id)
            .filter(EmbarqueItem.embarque_id == emb_id).all()
        ]
        if not item_ids_emb:
            continue
        items_emb = (
            db.query(ItemCotizacion)
            .filter(ItemCotizacion.id.in_(item_ids_emb))
            .all()
        )
        todos_despachados = all(i.estado_item == "despachado" for i in items_emb)
        if todos_despachados:
            emb = db.query(Embarque).filter(Embarque.id == emb_id).first()
            if emb and emb.estado != "despachado":
                emb.estado = "despachado"

    oc = d.oc_cliente
    if oc and oc.cotizacion:
        try:
            crear_notificacion(
                db,
                rol="ventas",
                severidad="info",
                titulo=f"Despacho {d.numero_despacho} completado",
                mensaje=f"OC {oc.numero_oc} - {oc.cotizacion.cliente} · {len(d.items)} ítems despachados",
                entidad_tipo="despacho",
                entidad_id=d.id,
                link=f"/despachos?id={d.id}",
                regla=f"despacho_completado_{d.id}",
            )
        except Exception:
            # don't fail the dispatch if notification fails
            pass

    db.commit()
    return {"ok": True, "numero_despacho": d.numero_despacho}


@router.post("/{despacho_id}/firmar")
def firmar_despacho(
    despacho_id: int,
    payload: FirmarIn,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Marca la guía de despacho como FIRMADA (entregada y firmada por el cliente).
    Solo con la guía firmada Contabilidad puede emitir la factura de esos ítems.

    FIRMA PARCIAL (payload.items): el operador ajusta CANTIDADES por ítem cuando la
    guía viajó con mercadería que el cliente NO recibió (perdida en la entrega). Lo
    firmado va a facturación; el faltante queda registrado con motivo y NO es
    facturable por esta guía. La reposición NO vuelve por esta venta (el dueño la
    pide en una cotización nueva): cero liberación de cupo, cero cambios de estado
    de línea, cero bodega. RE-FIRMA editable: se puede volver a llamar (el courier
    encontró la caja) mientras ninguna línea baje de lo YA FACTURADO por esa guía."""
    # Orden GLOBAL de locks de la casa: OC → despacho (igual que crear_factura y
    # eliminar_factura en contabilidad.py). Firmar corre contra crear_factura por la
    # misma venta: sin serializar por la OC, una re-firma a la baja y una factura
    # simultáneas podían leer el mismo "ya facturado" y dejar qty_firmada bajo lo
    # facturado (estado imposible). Hoy además firmar no tomaba NINGÚN lock.
    ref = db.query(Despacho).filter(Despacho.id == despacho_id).first()
    if not ref:
        raise HTTPException(404, "Despacho no encontrado")
    if ref.oc_cliente_id:
        db.query(OcCliente).filter(OcCliente.id == ref.oc_cliente_id).with_for_update().first()
    d = (
        db.query(Despacho)
        .filter(Despacho.id == despacho_id)
        .populate_existing()
        .with_for_update()
        .first()
    )
    if not d:
        raise HTTPException(404, "Despacho no encontrado")
    if d.estado != "despachado":
        raise HTTPException(400, "Primero confirme (cierre) el despacho; luego marque la guía como firmada")
    if payload.numero_guia:
        # Con guía electrónica viva, el N° correcto ya es el folio del SII: se
        # bloquea el reemplazo manual (la firma en sí sigue funcionando sin tocar el N°).
        _rechazar_si_pisa_folio(db, d, payload.numero_guia)
        d.numero_guia = payload.numero_guia
    fecha = None
    if payload.fecha_firma:
        try:
            fecha = datetime.strptime(payload.fecha_firma[:10], "%Y-%m-%d")
        except (ValueError, TypeError):
            fecha = None
    # La guía firmada (foto/PDF) es OBLIGATORIA: es el respaldo de la entrega y
    # la condición para que Contabilidad pueda facturar esos ítems.
    # RE-FIRMA sin archivo nuevo (revisión adversarial H1): se CONSERVA el que ya
    # está — el flujo «Editar firma» (el courier encontró la caja, corregir un tick
    # o el motivo) no obliga a re-subir la misma foto. En la PRIMERA firma sigue
    # siendo obligatoria.
    if not payload.archivo:
        if not (d.guia_firmada and d.guia_firmada_archivo):
            raise HTTPException(400, "Debes adjuntar la guía de despacho firmada por el cliente")
    elif not _exists_in_docs(payload.archivo):
        raise HTTPException(400, "El documento de la guía firmada no existe (súbalo primero)")

    # ── Firma parcial: validar y calcular las cantidades firmadas ──────────────
    # `nuevas`: despacho_item_id -> qty firmada declarada. Cada llamada declara el
    # estado COMPLETO de la firma (reemplazo): línea no listada = firmada completa.
    nuevas: dict = {}
    if payload.items is not None:
        di_map = {di.id: di for di in d.items}
        for entrada in payload.items:
            di = di_map.get(entrada.despacho_item_id)
            if di is None:
                raise HTTPException(
                    404, f"El ítem de despacho {entrada.despacho_item_id} no pertenece a este despacho")
            if entrada.despacho_item_id in nuevas:
                raise HTTPException(
                    400, f"El ítem de despacho {entrada.despacho_item_id} viene repetido en la firma")
            q = float(entrada.qty_firmada)
            qd = float(di.qty_despachada or 0.0)
            # `not (0 <= q <= qd)` también ataja NaN (toda comparación con NaN es falsa).
            if not (0.0 <= q <= qd + _TOL_QTY):
                it = di.item_cotizacion
                nombre = (it.numero_parte if it else None) or f"ítem {di.id}"
                raise HTTPException(
                    400, f"{nombre}: la cantidad firmada debe estar entre 0 y lo "
                         f"despachado ({qd:g}); llegó {entrada.qty_firmada}")
            nuevas[di.id] = min(q, qd)

    # Σ firmada EFECTIVA sobre TODAS las líneas (no listada = completa) y faltante.
    suma_firmada = 0.0
    suma_despachada = 0.0
    for di in d.items:
        qd = float(di.qty_despachada or 0.0)
        suma_despachada += qd
        suma_firmada += nuevas.get(di.id, qd) if payload.items is not None else qd
    if payload.items is not None and suma_firmada <= _TOL_QTY:
        raise HTTPException(
            400, "Una guía firmada donde no llegó nada no es una firma: si el cliente "
                 "no recibió ningún ítem, no marques la guía como firmada (gestiona la "
                 "entrega o anula la guía con Contabilidad)")
    faltante = max(suma_despachada - suma_firmada, 0.0)
    hay_faltante = faltante > _TOL_QTY

    # Motivo OBLIGATORIO ⇔ hay faltante (y solo entonces: un motivo sin faltante
    # dejaría registrada una explicación de algo que no pasó).
    motivo = (payload.motivo_faltante or "").strip()
    if hay_faltante:
        if len(motivo) < 5 or len(motivo) > 300:
            raise HTTPException(
                400, "Declara el motivo del faltante (5 a 300 caracteres): qué ítems no "
                     "llegaron y por qué (ej. caja perdida por el courier)")
    elif motivo:
        raise HTTPException(400, "No hay faltante declarado: no corresponde un motivo de faltante")

    # RE-FIRMA editable: ninguna línea puede quedar firmada por DEBAJO de lo ya
    # FACTURADO por ese despacho_item_id (la factura emitida es un documento vivo).
    # Import local para no acoplar los routers a nivel de módulo (mismo patrón que
    # wasabil_dte/router.py con routers.contabilidad).
    if payload.items is not None:
        from routers.contabilidad import (
            _qty_facturada_por_despacho_item, _qty_facturada_por_item,
        )
        fact_di = _qty_facturada_por_despacho_item(db, d.oc_cliente_id) if d.oc_cliente_id else {}
        for di in d.items:
            efectiva = nuevas.get(di.id, float(di.qty_despachada or 0.0))
            facturado = fact_di.get(di.id, 0.0)
            if efectiva + _TOL_QTY < facturado:
                it = di.item_cotizacion
                nombre = (it.numero_parte if it else None) or f"ítem {di.id}"
                raise HTTPException(
                    409, f"{nombre}: no puedes firmar {efectiva:g} porque esa guía ya "
                         f"tiene {facturado:g} facturado(s) de esa línea; elimina o "
                         "corrige la factura primero")
        # SEGUNDA CAPA por ÍTEM FÍSICO (revisión adversarial M1): las líneas de
        # factura con despacho_item_id NULL — que crear_factura persiste HOY cuando
        # se factura por ítems sueltos sin declarar guía — no aparecen en fact_di,
        # y con la sola capa de arriba una re-firma podía dejar «faltante» declarado
        # sobre unidades YA facturadas (facturado > firmado, el estado imposible).
        # Acá se compara por item_cotizacion_id contra TODO lo facturado de la
        # venta, que sí ve las líneas NULL. No es el agujero «legado» que decía el
        # comentario anterior: es alcanzable hoy sin carrera.
        if d.oc_cliente_id:
            fact_item = _qty_facturada_por_item(db, d.oc_cliente_id)
            firmada_oc: dict = {}
            despachos_oc = (db.query(Despacho)
                            .filter(Despacho.oc_cliente_id == d.oc_cliente_id,
                                    Despacho.estado == "despachado",
                                    Despacho.guia_firmada == 1)
                            .all())
            for desp in despachos_oc:
                for odi in desp.items:
                    if desp.id == d.id:
                        ef = nuevas.get(odi.id, float(odi.qty_despachada or 0.0))
                    else:
                        ef = _firmada_efectiva_di(odi)
                    firmada_oc[odi.item_cotizacion_id] = (
                        firmada_oc.get(odi.item_cotizacion_id, 0.0) + ef)
            ids_de_este = {di.item_cotizacion_id for di in d.items}
            for iid, facturado_it in fact_item.items():
                if firmada_oc.get(iid, 0.0) + _TOL_QTY < facturado_it                         and iid in ids_de_este:
                    it_nombre = next(
                        ((di.item_cotizacion.numero_parte
                          if di.item_cotizacion else None) or f"ítem {di.id}"
                         for di in d.items if di.item_cotizacion_id == iid),
                        f"ítem {iid}")
                    raise HTTPException(
                        409, f"{it_nombre}: no puedes dejar firmado menos de lo que "
                             f"la venta ya tiene facturado de esa parte "
                             f"({facturado_it:g}): elimina o corrige la factura "
                             "primero")

    # Aplicar. NULL = firma completa (canónico): se guarda número solo si es parcial.
    for di in d.items:
        if payload.items is None:
            di.qty_firmada = None
        else:
            q = nuevas.get(di.id)
            qd = float(di.qty_despachada or 0.0)
            di.qty_firmada = None if (q is None or q >= qd - _TOL_QTY) else q
    d.faltante_motivo = motivo if hay_faltante else None

    if payload.archivo:
        # Sin archivo nuevo en la RE-firma, se conserva el actual (H1): pisar con
        # None borraba el respaldo legal de la entrega en silencio.
        d.guia_firmada_archivo = payload.archivo
    d.guia_firmada = 1
    d.fecha_firma = fecha or datetime.now()
    d.usuario_firma_id = getattr(current_user, "id", None)
    db.commit()

    # Notificación POST-commit (la firma ya está a salvo: un fallo acá no la revierte).
    if hay_faltante:
        try:
            unidades = f"{faltante:g}"
            crear_notificacion(
                db,
                rol="contabilidad",
                severidad="warning",
                titulo=f"Guía {d.numero_guia or d.numero_despacho}: faltante en la entrega",
                mensaje=(f"Guía {d.numero_guia or d.numero_despacho}: faltante de "
                         f"{unidades} unidad(es) — {motivo}"),
                entidad_tipo="despacho",
                entidad_id=d.id,
                link=f"/despachos?id={d.id}",
                # La regla lleva la CANTIDAD (revisión L4): la dedup de 24 h es por
                # regla, y una re-firma que corrige el faltante el mismo día debe
                # re-avisar el número nuevo a contabilidad, no quedar muda.
                regla=f"firma_parcial_faltante_{d.id}_{unidades}",
            )
            db.commit()
        except Exception:
            # la notificación jamás voltea una firma ya comprometida
            db.rollback()

    resp = {
        "ok": True, "guia_firmada": True, "numero_guia": d.numero_guia,
        "guia_firmada_archivo": d.guia_firmada_archivo,
    }
    if payload.items is not None:
        # Solo la vía nueva agrega campos: la firma completa (sin items) responde
        # byte-igual a como respondía siempre.
        resp["faltante_total"] = round(faltante, 4)
        resp["faltante_motivo"] = d.faltante_motivo
    return resp


@router.delete("/{despacho_id}")
def anular_despacho(
    despacho_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    # Retry 1213/1205, igual que cerrar y crear (paridad inversa con
    # monza_router_despachos.py:1113-1121): anular lockea el DESPACHO primero y crear lockea
    # los ÍTEMS primero, así que un anular concurrente con una creación de la misma OC puede
    # caer víctima del deadlock. Sin el retry salía como 500.
    for _ in range(3):
        try:
            return _anular_despacho_tx(db, despacho_id, current_user)
        except OperationalError as e:
            db.rollback()
            code = getattr(getattr(e, "orig", None), "args", [None])[0]
            if code not in (1213, 1205):
                raise
    raise HTTPException(409, "Conflicto de concurrencia al anular el despacho: reintenta")


def _anular_despacho_tx(db: Session, despacho_id: int, current_user: User):
    # FOR UPDATE: serializa contra la emisión de la guía (que también bloquea el
    # despacho en _reclamar_emision) — sin el lock, anular y emitir simultáneos
    # podían dejar una guía SII viva sobre un despacho anulado.
    d = (
        db.query(Despacho)
        .filter(Despacho.id == despacho_id)
        .populate_existing()
        .with_for_update()
        .first()
    )
    if not d:
        raise HTTPException(404, "Despacho no encontrado")
    if d.estado != "en_preparacion":
        raise HTTPException(400, "Solo se pueden anular despachos en preparación")
    # La guía 52 se emite con el despacho aún en preparación: anular acá dejaría un
    # documento tributario legal huérfano y la mercadería libre para emitir OTRA
    # guía por lo mismo (doble emisión ante el SII). Se bloquea mientras la guía viva.
    # incluir_ambiguo=True: un claim VENCIDO sobre una emisión que Wasabil nunca
    # confirmó (uuid NULL + en_vuelo_desde puesto) también bloquea; si no, la
    # mercadería volvía a bodega y salía una SEGUNDA guía 52 REAL al SII. Se pasa SOLO
    # acá porque anular es irreversible (paridad con MonzaParts,
    # monza_router_despachos.py:_anular_despacho_tx).
    dte = _guia_electronica_activa(db, d.id, con_lock=True, incluir_ambiguo=True)
    if dte:
        if dte.folio:
            raise HTTPException(
                409,
                f"Este despacho tiene guía electrónica SII emitida (folio {dte.folio}): "
                "anúlala primero en Wasabil (anulación/nota de crédito) y luego anula el despacho",
            )
        if dte.uuid is None and dte.en_vuelo_desde is not None and not claim_vigente(dte):
            # Ambiguo con el claim vencido: "esperar" ya no resuelve nada, la única
            # salida es Reintentar (adopta el documento si existe en Wasabil, o
            # re-emite tras confirmar su ausencia). Mismo texto que el de facturas
            # (ambiguo_sin_resolver en routers/contabilidad.py).
            raise HTTPException(
                409,
                "No hay confirmación de Wasabil sobre esta emisión (se cortó la comunicación): "
                "la guía PUEDE existir ya ante el SII. Usa «Reintentar» para que el sistema lo "
                "verifique; si confirma que no se emitió, podrás anular",
            )
        raise HTTPException(
            409,
            "Este despacho tiene una emisión de guía SII en curso: espera el resultado "
            "(Emitida o Fallida) antes de anular",
        )
    d.estado = "anulado"
    # Simetría con cerrar_despacho: si este despacho sostenía (junto a otros) la
    # cobertura completa de una línea, al anularlo el remanente vuelve a bodega.
    # Con la cobertura por CERRADOS esto es casi inalcanzable (un cerrado no se
    # anula), pero queda como red de seguridad para datos legados.
    db.flush()
    qty_total = _qty_dispatched_closed(db, d.oc_cliente_id)
    for di in d.items:
        it = di.item_cotizacion
        if (
            it
            and it.estado_item == "despachado"
            and qty_total.get(it.id, 0) + 0.001 < (it.cantidad or 0)
        ):
            it.estado_item = "en_bodega"
    # DEFENSA (mesa redonda G16): la auto-transición del embarque a 'despachado'
    # era one-way. Si alguna línea de un embarque 'despachado' ya no está
    # despachada (reversa de arriba o estado atascado legado), el embarque vuelve
    # a 'en_bodega' — el estado que deja Bodega al cerrar la recepción. Solo BAJA,
    # nunca sube; los ítems nacionales (sin EmbarqueItem) simplemente no aplican.
    db.flush()
    item_ids_anulados = [di.item_cotizacion_id for di in d.items if di.item_cotizacion_id]
    if item_ids_anulados:
        emb_ids = {
            r[0] for r in db.query(EmbarqueItem.embarque_id)
            .filter(EmbarqueItem.item_cotizacion_id.in_(item_ids_anulados)).all()
        }
        for emb_id in emb_ids:
            emb = db.query(Embarque).filter(Embarque.id == emb_id).first()
            if not emb or emb.estado != "despachado":
                continue
            ids_emb = [
                r[0] for r in db.query(EmbarqueItem.item_cotizacion_id)
                .filter(EmbarqueItem.embarque_id == emb_id).all()
            ]
            items_emb = (
                db.query(ItemCotizacion).filter(ItemCotizacion.id.in_(ids_emb)).all()
                if ids_emb else []
            )
            if items_emb and not all(i.estado_item == "despachado" for i in items_emb):
                emb.estado = "en_bodega"
    db.commit()
    return {"ok": True}


# --- Serve documents uploaded via /api/compras/docs/upload ---
@router.get("/docs/{filename}")
def serve_doc(
    filename: str,
    current_user: User = Depends(get_current_user),
):
    """Serve a previously uploaded document. Authenticated access only.

    Path traversal is prevented by validating the filename format and resolving
    the final path against the uploads/docs directory.
    """
    # Strict filename validation: alphanumeric + dot + dash + underscore only
    if not re.match(r"^[A-Za-z0-9._-]{1,255}$", filename):
        raise HTTPException(400, "Nombre de archivo inválido")

    # Resolve and ensure it stays inside DOCS_DIR
    full_path = os.path.abspath(os.path.join(_DOCS_DIR, filename))
    if not full_path.startswith(_DOCS_DIR + os.sep):
        raise HTTPException(400, "Ruta inválida")
    if not os.path.isfile(full_path):
        raise HTTPException(404, "Documento no encontrado")

    return FileResponse(full_path, filename=filename)
