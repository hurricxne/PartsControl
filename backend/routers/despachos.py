# Antigüedad máxima aceptada para la fecha de emisión de una guía tecleada a mano. No es
# una regla del SII: es una malla ANCHA contra el dedazo grueso (un 2019 en vez de un
# 2026), y 2 años deja pasar cualquier regularización real.
# OJO — lo que esta malla NO ataja: el typo de UN año ("2025-07-15" por "2026-07-15") cae
# muy dentro de los 730 días y pasa limpio. Bajar el tope no es la solución (bloquearía
# regularizaciones legítimas); el control que sí ataja el error hacia adelante es el cruce
# `guia_fecha <= fecha de la factura` de armar_referencias_factura (wasabil_dte/service.py),
# porque una guía fechada el año pasado sigue siendo anterior a su factura y sólo el
# operador sabe si es correcta.
_ANTIGUEDAD_MAX_FECHA_GUIA_DIAS = 730

# Formato aceptado: AAAA-MM-DD, opcionalmente con sufijo horario ISO. Cualquier otra cosa
# pegada a la fecha se RECHAZA en vez de truncarse (ver _parse_fecha_guia).
_RE_FECHA_GUIA = re.compile(r"^\d{4}-\d{2}-\d{2}([T ].*)?$")


def _parse_fecha_guia(valor) -> Optional[date]:
    """Texto YYYY-MM-DD → date, para la fecha de EMISIÓN de la guía en papel.

    Devuelve None cuando el operador la borra (null o ""), que es un estado legítimo:
    el despacho vuelve a "sin fecha" y la facturación electrónica se bloquea hasta que
    se cargue de nuevo.

    Valida ANTES de guardar porque esta fecha termina viajando como FchRef dentro de un
    DTE 33 REAL: una fecha inventada no se corrige después, sólo se anula el documento.
    Se rechaza:
      · lo que no sea una fecha YYYY-MM-DD,
      · una fecha FUTURA (una guía no se emite mañana; suele ser un tipeo),
      · una fecha absurdamente vieja (ver _ANTIGUEDAD_MAX_FECHA_GUIA_DIAS).
    """
    if valor is None:
        return None
    texto = str(valor).strip()
    if not texto:
        return None
    # `_RE_FECHA_GUIA` antes de strptime: con `texto[:10]` a secas, "2026-07-155" se
    # truncaba a "2026-07-15" y se aceptaba en silencio un dato que el operador escribió
    # mal. Se admite el sufijo horario ("2026-07-15T10:00:00") porque algunos clientes
    # mandan datetime ISO, pero nada más pegado a la fecha.
    if not _RE_FECHA_GUIA.match(texto):
        raise HTTPException(
            400,
            "La fecha de emisión de la guía debe tener el formato AAAA-MM-DD "
            f"(recibido: '{texto}')",
        )
    try:
        fecha = datetime.strptime(texto[:10], "%Y-%m-%d").date()
    except ValueError:
        # Formato correcto pero fecha inexistente: 2026-02-31, 2026-13-01.
        raise HTTPException(
            400,
            f"La fecha de emisión de la guía '{texto[:10]}' no existe en el calendario",
        )
    hoy = hoy_chile()
    if fecha > hoy:
        raise HTTPException(
            400,
            f"La fecha de emisión de la guía ({fecha.isoformat()}) es futura: "
            "revisa el dato (hoy en Chile es "
            f"{hoy.isoformat()}). Debe ser la fecha en que el SII emitió la guía.",
        )
    if (hoy - fecha).days > _ANTIGUEDAD_MAX_FECHA_GUIA_DIAS:
        raise HTTPException(
            400,
            f"La fecha de emisión de la guía ({fecha.isoformat()}) tiene más de "
            f"{_ANTIGUEDAD_MAX_FECHA_GUIA_DIAS // 365} años: revisa el año antes de "
            "guardar (es el error de tipeo más común).",
        )
    return fecha


def _next_numero_despacho(db: Session) -> str:
    year = datetime.now().year
    prefix = f"DSP-{year}-"
    last = (
        db.query(Despacho)
        .filter(Despacho.numero_despacho.like(f"{prefix}%"))
        .order_by(Despacho.id.desc())
        .first()
    )
    n = 0
    if last and last.numero_despacho:
        try:
            n = int(last.numero_despacho.split("-")[-1])
        except Exception:
            n = 0
    return f"{prefix}{n + 1:04d}"


def _qty_already_dispatched(db: Session, oc_id: int, con_lock: bool = False):
    """Return dict {item_cotizacion_id: total_qty_despachada} for non-cancelled despachos

    `con_lock=True` (creación de despachos): lee con SELECT ... FOR UPDATE para ver
    las cantidades COMMITEADAS más recientes aunque la transacción tenga un snapshot
    anterior (REPEATABLE READ) — cierra la carrera de dos despachos simultáneos de
    la misma OC. `populate_existing()` obligatorio: sin él, el identity map de
    SQLAlchemy devolvería los datos viejos del snapshot aunque el lock espere.
    """
    q = (
        db.query(DespachoItem.item_cotizacion_id, DespachoItem.qty_despachada)
        .join(Despacho, Despacho.id == DespachoItem.despacho_id)
        .filter(Despacho.oc_cliente_id == oc_id, Despacho.estado != "anulado")
    )
    if con_lock:
        q = q.populate_existing().with_for_update()
    rows = q.all()
    result = {}
    for item_id, qty in rows:
        result[item_id] = result.get(item_id, 0) + (qty or 0)
    return result


def _qty_dispatched_closed(db: Session, oc_id: int, con_lock: bool = False):
    """Σ qty por ítem SOLO de despachos CERRADOS ('despachado').

    Es la cobertura que decide el flip de la línea (y del embarque) al cerrar un
    despacho: un despacho abierto (en_preparacion) es un borrador anulable, no
    mercadería salida — contarlo marcaba 'despachado' prematuro con tandas
    abiertas (hallazgo del enjambre G16). Para el TOPE anti-sobredespacho de
    create_despacho sigue siendo correcta _qty_already_dispatched (abiertos y
    cerrados consumen cupo por igual)."""
    q = (
        db.query(DespachoItem.item_cotizacion_id, DespachoItem.qty_despachada)
        .join(Despacho, Despacho.id == DespachoItem.despacho_id)
        .filter(Despacho.oc_cliente_id == oc_id, Despacho.estado == "despachado")
    )
    if con_lock:
        q = q.populate_existing().with_for_update()
    rows = q.all()
    result = {}
    for item_id, qty in rows:
        result[item_id] = result.get(item_id, 0) + (qty or 0)
    return result


# Estados de recepción cuyas unidades quedan UTILIZABLES en bodega. 'faltante'
# está incluido porque su qty_recibida son las unidades que SÍ llegaron buenas
# (el faltante se reclama aparte); 'no_llego' y 'danado_no_utilizable' aportan 0.
_RECEPCION_UTILIZABLE = ("completo", "danado_utilizable", "sobrante", "faltante")


def _qty_recibida_utilizable(db: Session, item_ids):
    """{item_cotizacion_id: Σ qty_recibida utilizable} desde recepciones CERRADAS.

    Es el TOPE FÍSICO del despacho: no se puede despachar (ni emitir guía, ni
    facturar) más de lo que Bodega recibió realmente. Solo aparecen los ítems
    que TIENEN registro de recepción — un ítem sin recepción (flujo antiguo o
    carga manual a bodega) no se acota, para no romper datos históricos.

    Suma DOS fuentes en el MISMO dict por item_cotizacion_id: (1) recepciones de
    EMBARQUE cerradas utilizables (internacional), (2) recepciones NACIONALES
    cerradas utilizables. Aditivo y direccionalmente seguro: para un ítem nacional
    solo puede BAJAR el tope (de 'todo lo vendido' a min(vendido, recibido)); no
    toca los internacionales (fuente distinta, item_ids disjuntos por construcción)."""
    if not item_ids:
        return {}
    result = {}
    # ── Fuente 1: embarques internacionales (SIN CAMBIOS) ──
    rows = (
        db.query(EmbarqueItem.item_cotizacion_id, RecepcionEmbarqueItem.qty_recibida)
        .join(RecepcionEmbarqueItem,
              RecepcionEmbarqueItem.embarque_item_id == EmbarqueItem.id)
        .join(RecepcionEmbarque,
              RecepcionEmbarque.id == RecepcionEmbarqueItem.recepcion_id)
        .filter(
            EmbarqueItem.item_cotizacion_id.in_(item_ids),
            RecepcionEmbarque.estado == "cerrada",
            RecepcionEmbarqueItem.estado_recepcion.in_(_RECEPCION_UTILIZABLE),
        )
        .all()
    )
    for item_id, qty in rows:
        result[item_id] = result.get(item_id, 0) + max(qty or 0, 0)
    # ── Fuente 2: recepciones NACIONALES (UNION aditivo) ──
    # Import LOCAL (patrón probado bodega→despachos): recepcion_nacional.models NO
    # importa despachos → sin ciclo. Se reusa la MISMA constante _RECEPCION_UTILIZABLE.
    from recepcion_nacional.models import RecepcionNacional, RecepcionNacionalItem
    nac = (
        db.query(RecepcionNacionalItem.item_cotizacion_id, RecepcionNacionalItem.qty_recibida)
        .join(RecepcionNacional,
              RecepcionNacional.id == RecepcionNacionalItem.recepcion_id)
        .filter(
            RecepcionNacionalItem.item_cotizacion_id.in_(item_ids),
            RecepcionNacional.estado == "cerrada",
            RecepcionNacionalItem.estado_recepcion.in_(_RECEPCION_UTILIZABLE),
        )
        .all()
    )
    for item_id, qty in nac:
        if item_id is None:
            continue
        # float() en ambos operandos: evita mezclar Decimal (fuente nacional) con
        # el valor previo (int/Decimal de la fuente 1) → nunca TypeError.
        result[item_id] = float(result.get(item_id, 0)) + max(float(qty or 0), 0.0)
    return result


def _tope_fisico(item: ItemCotizacion, recibidos: dict) -> float:
    """Cantidad máxima despachable de la línea: lo RECIBIDO en bodega si hay
    recepción registrada (capado a la cantidad vendida), o la cantidad de la
    cotización si no la hay (comportamiento histórico)."""
    cant = item.cantidad or 0
    if item.id in recibidos:
        return min(cant, recibidos[item.id])
    return cant


def _guia_electronica_activa(db: Session, despacho_id: int, con_lock: bool = False,
                             incluir_ambiguo: bool = False) -> Optional[WasabilDte]:
    """Guía electrónica (SII 52) VIVA del despacho: emitida, en vuelo (claim) o en
    proceso en Wasabil. Mientras exista, las operaciones que la dejarían huérfana o
    pisarían su folio (anular el despacho, editar el N° de guía a mano) se rechazan:
    el folio es un documento tributario legal y su anulación se gestiona en Wasabil.
    Un DTE FALLIDO (rechazado por el SII, sin folio) no bloquea nada.

    `con_lock=True` (anular): lee con FOR UPDATE + populate_existing para ver el
    claim/estado COMMITEADO más reciente aunque la transacción tenga un snapshot
    anterior — cierra la carrera anular ↔ emitir.

    `incluir_ambiguo=True` (SOLO anular): además cuenta como viva la emisión
    AMBIGUA — uuid NULL pero `en_vuelo_desde` puesto — aunque su claim ya haya
    VENCIDO por TTL. Ahí Wasabil cortó la comunicación sin confirmar nada
    (timeout/5xx) y `_emitir_en_wasabil` conserva el timestamp a propósito: el
    documento PUDO nacer con folio real en el SII. Decidir por TTL dejaba anular el
    despacho, liberaba la mercadería y habilitaba una SEGUNDA guía 52 REAL por lo
    mismo (irreversible — y Grupo AM es la marca que YA emite de verdad), además de
    dejar el documento sin recuperación. Es el mismo `ambiguo_sin_resolver` que ya
    protege el borrado de facturas en routers/contabilidad.py. El fallo CONFIRMADO
    no queda atrapado: _emitir_en_wasabil limpia `en_vuelo_desde` cuando el error NO
    es ambiguo, así que un DTE fallido sigue permitiendo anular (el despacho nunca
    es imborrable).
    Por defecto False: el PUT de numero_guia (_rechazar_si_pisa_folio) NO es
    irreversible y ahí el criterio por TTL es el correcto — no se debe endurecer.

    Paridad con MonzaParts (monza_router_despachos.py:_guia_electronica_activa)."""
    q = (
        db.query(WasabilDte)
        .filter(WasabilDte.despacho_id == despacho_id,
                WasabilDte.tipo_dte == TIPO_DOC_GUIA)
    )
    if con_lock:
        q = q.populate_existing().with_for_update()
    dte = q.first()
    if not dte:
        return None
    if dte.status_id == STATUS_EMITIDO:
        return dte
    if claim_vigente(dte):
        return dte
    if dte.uuid and dte.status_id in (STATUS_PROCESANDO, STATUS_PENDIENTE):
        return dte
    # Emisión AMBIGUA con el claim ya vencido: sin uuid no sabemos si el documento
    # existe, pero `en_vuelo_desde` dice que el POST salió y nadie confirmó el
    # resultado. Solo bloquea a quien lo pide (anular).
    if incluir_ambiguo and dte.uuid is None and dte.en_vuelo_desde is not None:
        return dte
    return None


def _rechazar_si_pisa_folio(db: Session, d: Despacho, numero_guia_nuevo: Optional[str]):
    """Bloquea el cambio manual de numero_guia cuando el despacho tiene guía
    electrónica viva (el N° correcto es el folio del SII, lo escribe el módulo
    Wasabil). Dejar pasar el mismo valor actual es inofensivo (no-op)."""
    if (numero_guia_nuevo or "") == (d.numero_guia or ""):
        return
    dte = _guia_electronica_activa(db, d.id)
    if not dte:
        return
    if dte.folio:
        raise HTTPException(
            409,
            f"Este despacho tiene guía electrónica SII emitida (folio {dte.folio}): "
            "el N° de guía no se edita a mano",
        )
    raise HTTPException(
        409,
        "Este despacho tiene una emisión de guía SII en curso: el N° de guía "
        "quedará fijado por el folio del SII al terminar",
    )


def _serialize_oc_card(db: Session, oc: OcCliente, items=None, clientes_por_rut=None):
    """Serialize OC-Cliente for the dispatch list view

    `items` / `clientes_por_rut` permiten precargar en lote desde el listado
    (una query para todas las OCs en vez de 2 por OC); sin ellos, consulta
    individualmente como siempre (detalle de una sola OC).
    """
    cot = oc.cotizacion
    if not cot:
        return None
    cliente = None
    if clientes_por_rut is not None:
        cliente = clientes_por_rut.get(cot.rut_cliente) if cot.rut_cliente else None
    elif cot.rut_cliente:
        cliente = db.query(Cliente).filter(Cliente.rut == cot.rut_cliente).first()

    if items is None:
        items = (
            db.query(ItemCotizacion)
            .filter(ItemCotizacion.cotizacion_id == cot.id)
            .all()
        )
    total = len(items)
    en_bodega = sum(1 for i in items if i.estado_item == "en_bodega")
    despachados = sum(1 for i in items if i.estado_item == "despachado")
    no_dispon = total - en_bodega - despachados

    # Pipeline state breakdown for progress bar
    progreso_estados = {b: 0 for b in _BUCKET_ORDER}
    for it in items:
        progreso_estados[_bucket_of(it.estado_item)] += 1

    # OC-level days remaining (customer-facing deadline)
    dias_restantes_oc: Optional[int] = None
    if oc.fecha_entrega:
        try:
            dias_restantes_oc = business_days_remaining(oc.fecha_entrega)
        except Exception:
            dias_restantes_oc = None

    # Worst-case (most urgent) item deadline — the most constraining promise
    worst_item_days: Optional[int] = None
    for it in items:
        if it.estado_item == "despachado":
            continue
        dl = _item_deadline(it, cot, oc)
        if not dl:
            continue
        try:
            d = business_days_remaining(dl)
        except Exception:
            continue
        if worst_item_days is None or d < worst_item_days:
            worst_item_days = d

    if total == 0:
        progreso = 0
    else:
        progreso = int(despachados * 100 / total)

    if total and despachados == total:
        estado = "completado"
    elif despachados > 0 and en_bodega > 0:
        estado = "parcial"
    elif en_bodega > 0:
        estado = "listo"
    else:
        estado = "pendiente"

    return {
        "id": oc.id,
        "cotizacion_id": cot.id,
        "numero_oc": oc.numero_oc,
        "fecha_oc": oc.fecha_oc,
        "fecha_entrega": oc.fecha_entrega.isoformat() if oc.fecha_entrega else None,
        "cond_pago": oc.cond_pago,
        "cliente": cot.cliente,
        "rut_cliente": cot.rut_cliente,
        "direccion": (cliente.direccion if cliente else None) or cot.direccion_cliente,
        "contacto": (cliente.contacto if cliente else None) or cot.contacto_cliente,
        "telefono": (cliente.telefono if cliente else None) or cot.telefono_cliente,
        "email": (cliente.email if cliente else None) or cot.email_cliente,
        "numero_cotizacion": cot.numero,
        "total_items": total,
        "items_en_bodega": en_bodega,
        "items_despachados": despachados,
        "items_no_disponibles": no_dispon,
        "progreso_pct": progreso,
        "progreso_estados": progreso_estados,
        "estado": estado,
        "dias_restantes_oc": dias_restantes_oc,
        "dias_restantes_critico": worst_item_days,
        "documentos": {
            "excel_oc": True,
            "cot_formal_excel": bool(cot.archivo_formal),
            "cot_pdf": True,
            "cot_original_excel": bool(cot.archivo_original),
        },
    }


