@router.put("/{despacho_id}")
def update_despacho(
    despacho_id: int,
    payload: DespachoUpdate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    d = db.query(Despacho).filter(Despacho.id == despacho_id).first()
    if not d:
        raise HTTPException(404, "Despacho no encontrado")
    if d.estado == "anulado":
        raise HTTPException(400, "No se puede editar un despacho anulado")
    # Los datos de cabecera (transportista, N° guía, N° de expedición, contacto, dirección,
    # observaciones) pueden completarse/corregirse aunque el despacho ya esté cerrado o firmado:
    # el N° de expedición suele llegar del courier DESPUÉS del despacho.
    data = payload.dict(exclude_unset=True)
    # Excepción: con guía electrónica viva, numero_guia es el folio del SII y no se pisa a mano.
    if "numero_guia" in data:
        _rechazar_si_pisa_folio(db, d, data["numero_guia"])
    # fecha_guia llega como texto y la columna es Date: se convierte y valida ANTES del
    # setattr genérico (si no, SQLAlchemy guardaría el string crudo). Se saca del dict para
    # que el bucle de abajo no la pise con el valor sin parsear.
    if "fecha_guia" in data:
        d.fecha_guia = _parse_fecha_guia(data.pop("fecha_guia"))
    for field, value in data.items():
        setattr(d, field, value)
    db.commit()
    return {"ok": True}


@router.post("/{despacho_id}/cerrar")
def cerrar_despacho(
    despacho_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    # Retry 1213/1205 (regla de la casa): cerrar ahora toma locks (despacho + ítems)
    # y puede caer víctima de un deadlock contra crear/anular concurrentes.
    for _ in range(3):
        try:
            return _cerrar_despacho_tx(db, despacho_id)
        except OperationalError as e:
            db.rollback()
            code = getattr(getattr(e, "orig", None), "args", [None])[0]
            if code not in (1213, 1205):
                raise
    raise HTTPException(409, "Conflicto de concurrencia al cerrar el despacho: reintenta")


def _cerrar_despacho_tx(db: Session, despacho_id: int):
    # FOR UPDATE sobre el despacho: serializa contra anular_despacho (que también
    # lockea) y contra la emisión de la guía. populate_existing(): datos frescos
    # aunque el snapshot REPEATABLE READ sea anterior.
    d = (
        db.query(Despacho)
        .filter(Despacho.id == despacho_id)
        .populate_existing()
        .with_for_update()
        .first()
    )
    if not d:
        raise HTTPException(404, "Despacho no encontrado")
    if d.estado != "en_preparacion":
        raise HTTPException(400, "Solo se pueden cerrar despachos en preparación")

    # Ancla canónica de la casa (patrón recepcion_nacional._cerrar): lockear los
    # ItemCotizacion afectados en UNA query, orden id ASC, antes de mutar estados.
    item_ids = sorted({di.item_cotizacion_id for di in d.items if di.item_cotizacion_id})
    if item_ids:
        (
            db.query(ItemCotizacion)
            .filter(ItemCotizacion.id.in_(item_ids))
            .order_by(ItemCotizacion.id.asc())
            .populate_existing()
            .with_for_update()
            .all()
        )

    # CERRAR PRIMERO y flush: la cobertura de abajo cuenta SOLO despachos cerrados
    # (incluido este). Sin esto, la última tanda nunca voltearía la línea; y contar
    # abiertos (bug G16) marcaba 'despachado' prematuro con tandas en preparación.
    d.estado = "despachado"
    d.fecha_despacho = datetime.now()
    db.flush()

    # Recolectar embarques afectados para evaluar auto-transición a "despachado"
    embarque_ids_afectados = set()
    # Cantidad acumulada por ítem en los despachos CERRADOS de la OC (incluye este).
    # La línea pasa a "despachado" solo cuando queda cubierta completa: un cierre
    # parcial deja el remanente en bodega, despachable y facturable después.
    qty_total = _qty_dispatched_closed(db, d.oc_cliente_id, con_lock=True)
    for di in d.items:
        it = di.item_cotizacion
        if it and it.estado_item == "en_bodega":
            if qty_total.get(it.id, 0) + 0.001 < (it.cantidad or 0):
                continue
            it.estado_item = "despachado"
            # Buscar el embarque que trajo este item
            ei = (
                db.query(EmbarqueItem)
                .filter(EmbarqueItem.item_cotizacion_id == it.id)
                .first()
            )
            if ei:
                embarque_ids_afectados.add(ei.embarque_id)

    # Auto-transición: si TODOS los items de un embarque están despachados,
    # marcar el embarque como "despachado"
    db.flush()
    for emb_id in embarque_ids_afectados:
        item_ids_emb = [
            r[0] for r in db.query(EmbarqueItem.item_cotizacion_id)
            .filter(EmbarqueItem.embarque_id == emb_id).all()
        ]
        if not item_ids_emb:
            continue
        items_emb = (
            db.query(ItemCotizacion)
            .filter(ItemCotizacion.id.in_(item_ids_emb))
            .all()
        )
        todos_despachados = all(i.estado_item == "despachado" for i in items_emb)
        if todos_despachados:
            emb = db.query(Embarque).filter(Embarque.id == emb_id).first()
            if emb and emb.estado != "despachado":
                emb.estado = "despachado"

    oc = d.oc_cliente
    if oc and oc.cotizacion:
        try:
            crear_notificacion(
                db,
                rol="ventas",
                severidad="info",
                titulo=f"Despacho {d.numero_despacho} completado",
                mensaje=f"OC {oc.numero_oc} - {oc.cotizacion.cliente} · {len(d.items)} ítems despachados",
                entidad_tipo="despacho",
                entidad_id=d.id,
                link=f"/despachos?id={d.id}",
                regla=f"despacho_completado_{d.id}",
            )
        except Exception:
            # don't fail the dispatch if notification fails
            pass

    db.commit()
    return {"ok": True, "numero_despacho": d.numero_despacho}


